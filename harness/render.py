"""Render a checked document as Markdown.

Each claim ends with its citations as links. The links jump to a "Code
references" appendix that quotes the cited lines, so the Markdown is
self-contained: a reader on GitHub can check every claim without opening the
notebook.

Text written by the model is rendered as plain text: no links, images or HTML can
come through. Otherwise a notebook could get the model to write an image whose
URL carries code to another server, fetched as soon as someone opens the
document on GitHub or Confluence.
"""

from __future__ import annotations

import re

from .notebook import Notebook, parse_citation

_CODE_SPAN = re.compile(r"(`+)(.+?)\1", re.S)
_URL = re.compile(r"\b(?:https?://|www\.)[^\s`<>()\[\]]*[^\s`<>()\[\].,;:!?]", re.I)

MARK = {"verified": "✓", "partial": "≈", "unchecked": "○", "unverified": "⚠", "invalid": "⚠"}
LEGEND = ("✓ verified: the quote and every name in the claim are in the cited lines · "
          "≈ partly supported · ○ unchecked: the claim names nothing that can be checked · "
          "⚠ not supported by the cited lines · ⚙ added by static analysis")
AUDIENCE_NAME = {"manager": "Manager", "developer": "Developer", "agent": "AI coding agent"}


def _anchor(cite: str) -> str:
    return cite.lower().replace(":", "-")


def plain(text: str) -> str:
    """Make model text inert as Markdown. Code spans stay (they render nothing)."""
    out, pos = [], 0
    for m in _CODE_SPAN.finditer(text):
        out.append(_escape(text[pos:m.start()]))
        out.append(m.group(0))
        pos = m.end()
    out.append(_escape(text[pos:]))
    return "".join(out).replace("\n", " ")


def _escape(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("[", "\\[").replace("]", "\\]")
    return _URL.sub(lambda m: f"`{m.group(0)}`", text)


def _fence(lines: list[str]) -> str:
    longest = max((len(run) for line in lines for run in re.findall(r"`+", line)), default=0)
    return "`" * max(3, longest + 1)


def _cite_label(nb: Notebook, cite: str, with_file_line: bool) -> str:
    parsed = parse_citation(cite)
    if not parsed or not with_file_line:
        return cite
    lines = nb.span_lines(*parsed)
    if lines and lines[0].file_line:
        return f"{cite} (file L{lines[0].file_line})"
    return cite


def render_markdown(nb: Notebook, doc: dict, report: dict | None = None) -> str:
    audience = doc.get("audience", "")
    with_file_line = audience == "agent"
    stats = doc.get("stats", {})
    provider = (report or {}).get("provider", {})
    out = [f"# {plain(doc['title'])}", ""]
    out.append(f"> For: **{AUDIENCE_NAME.get(audience, audience)}** · Notebook: `{nb.name}` "
               f"(sha256 `{nb.sha256[:12]}`) · Generated by notebook-explainer with "
               f"`{provider.get('name', '?')}` / `{provider.get('model', '?')}`")
    out.append(f"> Claims: {stats.get('claims', 0)} · verified {stats.get('verified', 0)} · partial "
               f"{stats.get('partial', 0)} · unchecked {stats.get('unchecked', 0)} · unverified "
               f"{stats.get('unverified', 0) + stats.get('invalid', 0)} · repaired {stats.get('repaired', 0)} · "
               f"added by static analysis {stats.get('static_added', 0)}")
    out.append(f"> {LEGEND}")
    out.append("> Citations are `C<cell>:L<line>`: cell number in the notebook, line number inside that cell.")
    out.append("")

    cited: list[str] = []
    for section in doc["sections"]:
        claims = [c for c in section["claims"] if c.get("status") != "dropped"]
        if not claims:
            continue
        out += [f"## {plain(section['heading'])}", ""]
        for c in claims:
            links = []
            for cite in c["citations"]:
                parsed = parse_citation(cite)
                exists = parsed and nb.span_lines(*parsed)
                label = _cite_label(nb, cite, with_file_line)
                if exists:
                    links.append(f"[{label}](#{_anchor(cite)})")
                    if cite not in cited:
                        cited.append(cite)
                else:
                    links.append(f"~~{cite}~~")
            mark = "⚙" if c.get("origin") == "static" else MARK.get(c.get("status", ""), "")
            kind = f"*{c['kind']}* · " if c.get("kind") not in (None, "fact") else ""
            out.append(f"- {kind}{plain(c['text'])} {' '.join(links)} {mark}".rstrip())
        out.append("")

    if cited:
        out += ["## Code references", ""]
        for cite in cited:
            c_idx, start, end = parse_citation(cite)
            lines = nb.span_lines(c_idx, start, end)
            cell = nb.cell(c_idx)
            file_note = f" · file lines {lines[0].file_line}-{lines[-1].file_line}" if lines[0].file_line else ""
            out.append(f'<a name="{_anchor(cite)}"></a>**{cite}** · cell {c_idx} ({cell.lang}){file_note}')
            out.append("")
            shown = lines[:15]
            body = [f"{line.n:>3}  {line.text}" for line in shown]
            fence = _fence(body)
            lang = "sql" if cell.lang == "sql" else ("python" if cell.lang == "python" else "")
            out.append(f"{fence}{lang}")
            out += body
            if len(lines) > len(shown):
                out.append(f"     … {len(lines) - len(shown)} more lines")
            out.append(fence)
            out.append("")
    return "\n".join(out).rstrip() + "\n"
